#!/usr/bin/env bash
# ─────────────────────────────────────────────────────────────────────────────
# Ночная копия боевой базы Кино Базы.
#
# Копия снимается командой sqlite3 «.backup», а не «cp»: база работает в режиме WAL,
# и обычное копирование файла даёт снимок без последних записей — то есть тихо
# отставший на неизвестное число правок. «.backup» снимает согласованный снимок
# прямо во время работы приложения, останавливать службу не нужно.
#
# Установка (на сервере, от root):
#   install -m 700 ops/backup-db.sh /usr/local/bin/kinobase-backup.sh
#   crontab -e   # строка — в конце файла
#
# Скрипт кладётся в /usr/local/bin, а не запускается из каталога кода: выкатка
# переносит код через rsync --delete, и задание cron не должно зависеть от того,
# что происходит в этот момент с рабочим деревом.
#
# Настройки можно переопределить переменными окружения в строке cron.
# ─────────────────────────────────────────────────────────────────────────────
set -euo pipefail

DB="${DB:-/var/lib/kinobase/kinobaza.db}"
DEST="${DEST:-/var/backups/kinobase}"
KEEP_DAYS="${KEEP_DAYS:-14}"

if [ ! -f "$DB" ]; then
  echo "Базы нет: $DB" >&2
  exit 1
fi

mkdir -p "$DEST"
OUT="$DEST/kinobaza-$(date +%F-%H%M).db"

sqlite3 "$DB" ".backup '$OUT'"
chmod 600 "$OUT"

# Копия проверяется сразу: битый файл, замеченный через две недели, — это две недели
# ложного спокойствия. quick_check читает страницы, не разворачивая всю базу.
CHECK=$(sqlite3 "$OUT" 'pragma quick_check;')
if [ "$CHECK" != "ok" ]; then
  echo "Копия не прошла проверку ($CHECK): $OUT" >&2
  exit 1
fi

FILMS=$(sqlite3 "$OUT" 'select count(*) from films;')
echo "$(date +%F\ %H:%M) копия $OUT, тайтлов: $FILMS"

# Ротация. Под гребёнку идут и копии, которые снимает deploy.sh перед каждой выкаткой:
# лежат они в том же каталоге и стареют так же.
find "$DEST" -maxdepth 1 -type f \
  \( -name 'kinobaza-*.db' -o -name 'before-deploy-*.db' \) \
  -mtime "+$KEEP_DAYS" -delete

# ─── Строка crontab (от root) ────────────────────────────────────────────────
# 0 4 * * * /usr/local/bin/kinobase-backup.sh >> /var/log/kinobase-backup.log 2>&1
#
# Четыре утра — время, когда сайт никто не читает. Вывод уезжает в лог, и это же
# способ убедиться, что задание вообще отрабатывает: пустой лог наутро означает,
# что копий нет, а не что всё хорошо.
