/** Ключ тайтла для скриптов наполнения — оригинальное название.
 *
 *  По русскому названию искать нельзя: «Призрак в доспехах» 1995 года и одноимённый
 *  сериал 2026-го — разные тайтлы с одним именем, и `Map` по `titleRu` молча оставил
 *  бы от двух записей одну. Правило действует в `add-films`, `tag-films`,
 *  `fill-seasons`, `fill-dossiers`, `refresh-films`, `fill-people` и `check-db`;
 *  у каждой записи в файлах данных есть поле `titleOriginal`.
 *
 *  До 15.09.2026 правило стояло шестью дословными копиями в самих скриптах, а ещё
 *  дважды — выражением внутри `.map(...)` без функции. Копии одного суждения
 *  расходятся молча, поэтому живёт оно здесь одно.
 *
 *  Функция в `src/lib`, а не в `scripts`: её читает `check-db`, и по README словари,
 *  от которых зависит запись в базу, лежат тут.
 *
 *  `??`, а не `||`: пустая строка — не «названия нет», а «название пустое», и
 *  подменять её русским значило бы прятать дефект файла от `check-data`. */
export function filmKey(film: { titleRu: string; titleOriginal?: string | null }): string {
  return film.titleOriginal ?? film.titleRu;
}
