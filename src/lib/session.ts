import { cookies } from 'next/headers';
import { GUEST_VIEW_COOKIE, isOwner, OWNER_COOKIE } from './owner';

/** Настоящая сессия: **кто** прислал запрос.
 *
 *  Вне боевой сборки — всегда владелец. Локальная база это личная копия владельца
 *  на его же машине: гостя там нет и быть не может, а требовать вход в собственную
 *  базу на `localhost` — обряд без смысла. Разделение гостя и владельца проверяют
 *  тесты и сам боевой сервер, то есть места, где оно что-то значит.
 *
 *  Режим «глазами гостя» на этот вопрос не влияет: владелец в нём остаётся
 *  владельцем, иначе снять режим было бы некому.
 *
 *  Секрет читается при каждом вызове, а не при загрузке модуля: служба получает
 *  его из окружения, и чтение на верхнем уровне заморозило бы значение,
 *  прочитанное до подстановки. */
export async function ownerSession(): Promise<boolean> {
  if (process.env.NODE_ENV !== 'production') return true;

  const jar = await cookies();
  return isOwner(jar.get(OWNER_COOKIE)?.value, process.env.OWNER_TOKEN);
}

/** Включён ли просмотр глазами гостя.
 *
 *  Работает и вне боевой сборки — в отличие от признака владельца. Посмотреть
 *  на сайт глазами читателя нужно там, где сайт и собирают. */
export async function guestViewOn(): Promise<boolean> {
  return (await cookies()).get(GUEST_VIEW_COOKIE)?.value === '1';
}

/** **Чьими глазами** смотрит тот, кто прислал текущий запрос.
 *
 *  Владелец, включивший режим гостя, отвечает «нет» — и отвечает всем сразу:
 *  страницам, подвалу, стражу серверного действия. В этом и смысл
 *  разделения: режим не прячет владельца вёрсткой, а делает его гостем на время
 *  просмотра. Иначе проверка «как это выглядит для читателя» проверяла бы вёрстку
 *  и молчала о том, ради чего затевалась. */
export async function viewerIsOwner(): Promise<boolean> {
  return (await ownerSession()) && !(await guestViewOn());
}
