/** Есть ли у тайтла комментарий владельца.
 *
 *  Предикат о данных, а не о вёрстке, — поэтому живёт здесь, рядом с `hasDossier`:
 *  его читают и карточка фильма, и редактор комментария, и разойтись они не должны.
 *
 *  Обрезка внутри проверки — страховка прошлого. До четырнадцатой версии стёртый
 *  комментарий сохранялся пустой строкой, и такие строки в живой базе уже лежат;
 *  валидатор чинит будущее, предикат — прошлое. */
export function hasComment(comment: string | null): comment is string {
  return comment !== null && comment.trim() !== '';
}
