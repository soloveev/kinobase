/** Слаг папки архива и сопоставление её с тайтлом.
 *
 *  До 15.09.2026 это знание жило в `src/lib/check-dossier.ts` — но только исторически:
 *  к рубрикам, врезкам и правовой рамке слаг отношения не имеет, а пользуются им два
 *  скрипта проверки напрямую. `check-dossier.ts` продолжает реэкспортировать
 *  `slugArchive` и `matchesArchiveFolder`, чтобы скрипты не переписывались
 *  одновременно с переездом. */

/** Транслитерация кириллицы для слага папки архива. Схема прочитана с живого материала,
 *  а не выбрана из справочника: этими парами в `research/` уже названы файлы архивов —
 *  `bolshoy`, `padalshchikov`, `poteryavshiesya`, `kuryokhin`, `umryom`, `vozvrashchenie`.
 *  Формально это практическая транслитерация, близкая к BGN/PCGN, но без позиционных
 *  правил: `е` всегда `e`, а не `ye` после гласной. Позиционные правила здесь лишние —
 *  слаг опознаёт папку, а не восстанавливает написание.
 *
 *  Разбор спорных мест и довод по каждому — в `research/SOURCING.md`, раздел «Устройство
 *  архива»; повторять их здесь незачем. Коротко о том, от чего зависит код: `й` даёт `y`,
 *  потому что папка `research/nepokoy` уже так называется; `ь` и `ъ` пропадают целиком,
 *  а не превращаются в дефис, потому что дефис означает границу слова и `bol-shoy` соврал
 *  бы про неё, заодно дав ложный хвост правилу «слаг оканчивается на `-<папка>`». */
const CYRILLIC_TO_LATIN: Record<string, string> = {
  а: 'a', б: 'b', в: 'v', г: 'g', д: 'd', е: 'e', ё: 'yo', ж: 'zh', з: 'z',
  и: 'i', й: 'y', к: 'k', л: 'l', м: 'm', н: 'n', о: 'o', п: 'p', р: 'r',
  с: 's', т: 't', у: 'u', ф: 'f', х: 'kh', ц: 'ts', ч: 'ch', ш: 'sh',
  щ: 'shch', ъ: '', ы: 'y', ь: '', э: 'e', ю: 'yu', я: 'ya',
};

/** Имя папки архива, выведенное из оригинального названия тайтла. Поля со слагом
 *  в данных нет, и папка опознаётся по нему: `research/odyssey` при «The Odyssey»,
 *  `research/camp-miasma` при «Teenage Sex and Death at Camp Miasma».
 *
 *  Диакритика снимается до отбрасывания лишнего, иначе теряется буква вместе со знаком:
 *  «Sirât» давал `sir-t`, папка `research/sirat` не сопоставлялась ни целиком, ни хвостом,
 *  и написания по этому архиву не сверялись. Скрипт при этом честно печатал строку
 *  о неопознанной папке — правило «неопознанная папка не проверяется молча» и показало
 *  дефект на первом же тайтле с диакритикой.
 *
 *  Кириллица транслитерируется, а не выбрасывается. Прежде она выбрасывалась, и у тайтла
 *  с кириллическим оригинальным названием слаг выходил **пустой строкой** — а пустая
 *  строка не равна ни одному имени папки и не оканчивается ни на какое `-<папка>`, то есть
 *  сопоставить архив было нельзя в принципе, и переименование папки не помогало. Пришёл
 *  «Непокой» (оригинальное название тоже «Непокой», архив в `research/nepokoy`), и сверки
 *  написаний, рифм и цитат по нему не выполнялись вовсе. Критерий отменён 31.08.2026.
 *
 *  Порядок шагов значащий, и переставить их нельзя. `й` и `ё` в NFD раскладываются на
 *  букву со знаком (`и` + U+0306, `е` + U+0308), поэтому снятие диакритики до
 *  транслитерации молча превратило бы их в `i` и `e`: «Непокой» дал бы `nepokoi` и снова
 *  промахнулся мимо папки. Отсюда: собрать составную форму (NFC) → транслитерировать
 *  кириллицу → и только потом снимать диакритику с того, что осталось латиницей. */
/** Буквы, которые выглядят латинскими с надстрочным знаком, но им не являются: `ø`, `ß`,
 *  `ł` и прочие — это самостоятельные знаки алфавита, и NFD их не разлагает. Без этой карты
 *  такая буква не теряет форму, а исчезает целиком вместе со служебными символами.
 *
 *  Ограничение было известно и записано тестом как безобидное: тайтла с такой буквой в базе
 *  нет, чинить заранее незачем. 06.09.2026 он появился — «Jo Nesbø's Detective Hole», —
 *  и отказ вышел молчаливым ровно так, как молчал он у «Сирата» и «Непокоя»: слаг стал
 *  `jo-nesb-s-detective-hole`, папка `research/jo-nesbos-detective-hole` не сопоставилась,
 *  и сверки по таблице фактов не выполнялись вовсе. */
const STANDALONE_TO_LATIN: Record<string, string> = {
  'ø': 'o',
  'æ': 'ae',
  'œ': 'oe',
  'ß': 'ss',
  'ł': 'l',
  'đ': 'd',
  'ð': 'd',
  'þ': 'th',
};

export function slugArchive(title: string): string {
  const latin = title
    .normalize('NFC')
    .toLowerCase()
    .replace(/[а-яё]/g, (letter) => CYRILLIC_TO_LATIN[letter] ?? letter)
    .replace(/[øæœßłđðþ]/g, (letter) => STANDALONE_TO_LATIN[letter])
    .replace(/['’]/g, '');

  return latin
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '');
}

/** Сходится ли папка архива с тайтлом. Имя папки бывает короче названия — `research/odyssey`
 *  при «The Odyssey», — поэтому сходится либо весь слаг, либо его хвост по границе дефиса.
 *
 *  Живёт здесь, а не в скриптах, потому что это одно суждение со `slugArchive` и меняться
 *  они будут вместе: слаг без правила сопоставления бессмыслен. До 31.08.2026 правило
 *  стояло двумя дословными копиями в `check-dossier.ts` и `check-dossier-one.ts`, и две
 *  копии одного суждения расходятся молча. */
export function matchesArchiveFolder(title: string, folder: string): boolean {
  const slug = slugArchive(title);
  return slug === folder || slug.endsWith(`-${folder}`);
}
