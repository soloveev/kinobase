// Слаг папки архива и сопоставление её с тайтлом.
//
// Рефакторинг 15.09.2026, находка 14 (specs/refactor-2026-09-15/audit-code.md): знание
// о слаге переезжает из `src/lib/check-dossier.ts` в собственный модуль
// `src/lib/archive-slug.ts` вместе с обеими таблицами букв и обеими функциями.
// В файле проверок формы досье оно жило только исторически: к рубрикам, врезкам
// и правовой рамке слаг отношения не имеет, а пользуются им два скрипта проверки
// напрямую. `check-dossier.ts` продолжает реэкспортировать `matchesArchiveFolder`,
// чтобы скрипты не переписывались одновременно с переездом.
//
// Контракт:
//   export function slugArchive(title: string): string
//   export function matchesArchiveFolder(title: string, folder: string): boolean
//   из '@/lib/archive-slug'.
//
// Тесты перенесены из tests/check-dossier.test.ts (там их было около двадцати) без
// изменения ожиданий: переезд ничего в поведении не меняет. Изменилось одно — правило
// сопоставления проверяется теперь настоящей функцией из библиотеки, а не третьей
// копией правила, написанной в самом тесте.

import { describe, it, expect } from 'vitest';
import { slugArchive, matchesArchiveFolder } from '@/lib/archive-slug';

// Слаг архива к тайтлу. Поля со слагом в данных нет, и папка опознаётся по имени,
// выведенному из оригинального названия. До захода по «Сирату» диакритика вырезалась
// вместе с буквой: `Sirât` давал `sir-t`, папка `research/sirat` не сопоставлялась
// ни целиком, ни хвостом, и написания по этому архиву молча не сверялись. Скрипт
// напечатал строку о неопознанной папке — то есть правило «неопознанная папка не
// проверяется молча» отработало и показало дефект.
describe('slugArchive: имя папки архива выводится из названия', () => {
  it('диакритика теряет знак, а не букву', () => {
    expect(slugArchive('Sirât')).toBe('sirat');
    expect(slugArchive('Amélie')).toBe('amelie');
    expect(slugArchive('El Niño')).toBe('el-nino');
    expect(slugArchive('Sátántangó')).toBe('satantango');
  });

  // Прежде эти буквы слаг ломали, и ограничение было записано тестом как известное:
  // «тайтла с ними в базе нет, чинить заранее незачем». 06.09.2026 такой тайтл появился —
  // «Jo Nesbø's Detective Hole», — и молчаливый отказ обнаружился на нём: слаг вышел
  // `jo-nesb-s-detective-hole`, папка архива не сопоставилась, и проверки по таблице
  // фактов не выполнялись вовсе, а `check-dossier-one` печатал «таблица фактов: НЕТ».
  it('самостоятельная буква теряет свою форму, а не саму себя', () => {
    expect(slugArchive('Jo Nesbø\'s Detective Hole')).toBe('jo-nesbos-detective-hole');
    expect(slugArchive('Der Fußgänger')).toBe('der-fussganger');
    expect(slugArchive('Æon Flux')).toBe('aeon-flux');
    expect(slugArchive('Łódź')).toBe('lodz');
  });

  // Апостроф — не разделитель слов, а знак внутри слова: «Widow's Bay» это два слова,
  // а не три. Прежде он превращался в дефис и давал `widow-s-bay` при папке `widows-bay`.
  it('апостроф исчезает, а не разрывает слово', () => {
    expect(slugArchive("Widow's Bay")).toBe('widows-bay');
    expect(slugArchive('Good Luck, Have Fun, Don\u2019t Die')).toBe(
      'good-luck-have-fun-dont-die',
    );
  });

  it('обычное название не меняется', () => {
    expect(slugArchive('Teenage Sex and Death at Camp Miasma')).toBe(
      'teenage-sex-and-death-at-camp-miasma',
    );
    expect(slugArchive('The Odyssey')).toBe('the-odyssey');
  });

  // ~~«кириллица слага не даёт: папка называется по оригинальному названию»~~ — критерий
  // отменён 31.08.2026. Прежнее правило писалось, когда тайтла с кириллическим оригиналом
  // в базе не было, и фиксировало ограничение как осознанную норму: слаг пустой, зато
  // папку всегда можно назвать оригинальным названием. Для русского фильма это
  // невыполнимо. Папки в `research/` называются латиницей, а пустая строка не равна
  // ни одному имени и не оканчивается ни на какое `-<папка>` — сопоставлять не с чем
  // в принципе, и переименование папки не помогает. Пришёл «Непокой» (оригинальное
  // название тоже «Непокой», архив в `research/nepokoy`), и сверки написаний, рифм
  // и цитат по нему не выполнялись вовсе. Отсюда транслитерация ниже. Это не регрессия:
  // критерий изменён осознанно, прежняя формулировка оставлена зачёркнутой.
  it('кириллица даёт слаг, а не пустую строку', () => {
    expect(slugArchive('Сират')).toBe('sirat');
  });

  it('служебные знаки схлопываются, края обрезаются', () => {
    expect(slugArchive('Alien: Earth')).toBe('alien-earth');
    expect(slugArchive('  Weapons  ')).toBe('weapons');
  });

  // Схема транслитерации кириллицы — та, которой в `research/` уже названы файлы архивов:
  // `bolshoy`, `padalshchikov`, `poteryavshiesya`, `kuryokhin`, `umryom`, `vozvrashchenie`.
  // Она не выбрана из справочника, а прочитана с живого материала, и в этом её довод:
  // папки и файлы агенты называют так уже сейчас, а `research/nepokoy` существует и
  // переименован не будет. Формально это практическая («популярная») транслитерация,
  // близкая к BGN/PCGN, но без позиционных правил: `е` всегда `e`, а не `ye` после гласной.
  // Позиционные правила здесь лишние — слаг опознаёт папку, а не восстанавливает написание.
  //
  //   а a  б b  в v  г g  д d  е e  ё yo  ж zh  з z  и i  й y  к k  л l  м m  н n
  //   о o  п p  р r  с s  т t  у u  ф f  х kh  ц ts  ч ch  ш sh  щ shch
  //   ъ —  ы y  ь —  э e  ю yu  я ya
  //
  // Спорные места решены так и здесь же закреплены, чтобы следующий агент назвал папку
  // правильно до того, как что-то сломается, а не после:
  //   • `й` → `y`, потому что папка `research/nepokoy` уже так называется; `j` и `i`
  //     из других схем дали бы `nepokoj` и `nepokoi` — ни то ни другое не сопоставится;
  //   • `ы` → тоже `y`: слаг — имя папки, а не обратимая запись, и совпадение двух букв
  //     в одной латинской ничему не мешает;
  //   • `ё` → `yo`, а не `e`: `kuryokhin` и `umryom` в архиве написаны так;
  //   • `х` → `kh`, а не `h`: одиночная `h` слилась бы с `sh`/`ch`/`zh` и «сходил» стало
  //     бы неотличимо от «шодил»;
  //   • `ц` → `ts` (в архиве встречается и `c`, но `ts` там же и преобладает);
  //   • `ь` и `ъ` пропадают целиком, а не превращаются в дефис: дефис в слаге означает
  //     границу слова, и `bol-shoy` соврал бы про неё — а заодно дал бы ложный хвост
  //     для правила «слаг оканчивается на `-<папка>`».
  it('кириллическая буква даёт свою латинскую пару', () => {
    const table: [string, string][] = [
      ['а', 'a'],
      ['б', 'b'],
      ['в', 'v'],
      ['г', 'g'],
      ['д', 'd'],
      ['е', 'e'],
      ['ё', 'yo'],
      ['ж', 'zh'],
      ['з', 'z'],
      ['и', 'i'],
      ['й', 'y'],
      ['к', 'k'],
      ['л', 'l'],
      ['м', 'm'],
      ['н', 'n'],
      ['о', 'o'],
      ['п', 'p'],
      ['р', 'r'],
      ['с', 's'],
      ['т', 't'],
      ['у', 'u'],
      ['ф', 'f'],
      ['х', 'kh'],
      ['ц', 'ts'],
      ['ч', 'ch'],
      ['ш', 'sh'],
      ['щ', 'shch'],
      ['ъ', ''],
      ['ы', 'y'],
      ['ь', ''],
      ['э', 'e'],
      ['ю', 'yu'],
      ['я', 'ya'],
    ];

    for (const [letter, latin] of table) {
      expect(slugArchive(letter), `буква ${letter}`).toBe(latin);
    }
  });

  // Главный случай, ради которого всё делается: русская полнометражная анимация, у которой
  // оригинальное название совпадает с русским, архив лежит в `research/nepokoy`.
  it('«Непокой» даёт nepokoy', () => {
    expect(slugArchive('Непокой')).toBe('nepokoy');
  });

  // Ловушка порядка операций. `й` и `ё` в NFD раскладываются на букву со знаком
  // (`и` + U+0306, `е` + U+0308), и снятие диакритики до транслитерации молча превращает
  // их в `i` и `e`: «Непокой» стал бы `nepokoi` и мимо папки. Значит, кириллица
  // транслитерируется по составленной форме, а диакритика снимается уже после — с того,
  // что осталось латиницей. Вход в разложенной форме тоже обязан пережить: JSON пишет
  // агент, и NFD оттуда прийти может.
  it('й и ё не теряют своей второй буквы на снятии диакритики', () => {
    expect(slugArchive('Ёжик в тумане')).toBe('yozhik-v-tumane');
    expect(slugArchive('Йошкар-Ола')).toBe('yoshkar-ola');
    expect(slugArchive('Непокой'.normalize('NFD'))).toBe('nepokoy');
  });

  // Мягкий и твёрдый знаки исчезают внутри слова, не разрывая его дефисом.
  it('ь и ъ пропадают, а не разрывают слово', () => {
    expect(slugArchive('Большой')).toBe('bolshoy');
    expect(slugArchive('Подъезд')).toBe('podezd');
  });

  it('заглавная кириллица приводится к строчной', () => {
    expect(slugArchive('НЕПОКОЙ')).toBe('nepokoy');
    expect(slugArchive('ЁЖИК В ТУМАНЕ')).toBe('yozhik-v-tumane');
    expect(slugArchive('Щи')).toBe('shchi');
  });

  // Смешанные названия в базе законны: «Ампир V» — русский тайтл с латинской буквой
  // в оригинальном названии.
  it('кириллица и латиница в одном названии уживаются', () => {
    expect(slugArchive('Ампир V')).toBe('ampir-v');
    expect(slugArchive('Хардкор Hardcore')).toBe('khardkor-hardcore');
  });

  // Служебные знаки при кириллице ведут себя ровно как при латинице: схлопываются
  // в дефис, края обрезаются. Кавычки-ёлочки — не диакритика и не буква, они выпадают
  // вместе с двоеточием; подряд идущие знаки дают один дефис, а не цепочку.
  it('служебные знаки при кириллице схлопываются так же', () => {
    expect(slugArchive('Дау: Наташа')).toBe('dau-natasha');
    expect(slugArchive('«Непокой»')).toBe('nepokoy');
    expect(slugArchive('Кин-дза-дза!')).toBe('kin-dza-dza');
    expect(slugArchive('  Непокой  ')).toBe('nepokoy');
  });

  // Правило сопоставления папки с тайтлом: слаг равен имени папки либо оканчивается
  // на `-<папка>` (короткое имя при длинном названии: `research/odyssey` при «The Odyssey»).
  // В тестируемую функцию оно не вынесено — живёт двумя одинаковыми копиями в
  // `scripts/check-dossier.ts` и `scripts/check-dossier-one.ts`, — поэтому здесь стоит
  // третья копия. Переносить логику из скриптов тесты не вправе, но само свойство,
  // от которого зависит сопоставление, проверить обязаны: без него «слаг стал непустым»
  // ничего ещё не доказывает.
  // Правило сопоставления папки с тайтлом: слаг равен имени папки либо оканчивается
  // на `-<папка>` (короткое имя при длинном названии: `research/odyssey` при «The Odyssey»).
  // Оно живёт рядом со слагом, потому что это одно суждение с ним: слаг без правила
  // сопоставления бессмыслен. До 31.08.2026 правило стояло двумя дословными копиями
  // в `check-dossier.ts` и `check-dossier-one.ts`, а тест держал третью — и проверял
  // не то, чем пользуются скрипты. Теперь проверяется сама функция.
  it('слаг «Непокоя» сопоставляется с папкой research/nepokoy', () => {
    expect(matchesArchiveFolder('Непокой', 'nepokoy')).toBe(true);
  });

  it('короткое имя папки сходится с хвостом длинного названия', () => {
    expect(matchesArchiveFolder('The Odyssey', 'odyssey')).toBe(true);
    expect(matchesArchiveFolder('Teenage Sex and Death at Camp Miasma', 'camp-miasma')).toBe(true);
  });

  // Хвост считается по границе дефиса, а не по буквам: иначе `research/ssey` сошлось бы
  // с «The Odyssey», и архив достался бы чужому тайтлу молча.
  // Ожидание «`miasma` не сходится с „Camp Miasma“» отсюда снято решением координатора
  // 15.09.2026: оно появилось при переезде тестов сверх спецификации (переезд поведения
  // не меняет), а по действующему правилу `-miasma` — законный хвост по границе дефиса,
  // такой же, как `-camp-miasma` строкой выше. Ужесточать правило — отдельное решение владельца.
  it('совпадение не по границе слова сопоставлением не считается', () => {
    expect(matchesArchiveFolder('The Odyssey', 'ssey')).toBe(false);
  });

  it('чужая папка не сопоставляется', () => {
    expect(matchesArchiveFolder('Weapons', 'nepokoy')).toBe(false);
  });

  // Почему пустой слаг был не «мелким неудобством», а полным отказом проверки: пустая
  // строка не равна ни одному имени папки и не оканчивается ни на какое `-<папка>`,
  // так что сопоставить её нельзя ни с чем — ни переименованием, ни вручную. Название
  // из одних служебных знаков — единственный оставшийся способ получить пустой слаг.
  it('пустой слаг не сопоставляется ни с одной папкой', () => {
    expect(slugArchive('!!!')).toBe('');

    for (const folder of ['nepokoy', 'sirat', 'weapons', 'camp-miasma']) {
      expect(matchesArchiveFolder('!!!', folder), folder).toBe(false);
    }
  });
});
