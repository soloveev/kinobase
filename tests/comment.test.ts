// Основание критериев приёмки 1 и 15 версии v14 — предикат «комментарий есть».
//
// Спека, раздел A: «Пустой комментарий по-прежнему не показывается никому: блока просто
// нет, а не стоит заглушка». Признак, по которому блок показывается или не показывается,
// один на весь проект и живёт в '@/lib/comment' — по образцу `hasDossier` из '@/lib/dossier':
// предикат о данных принадлежит библиотеке, а не вёрстке. Его читают и страница фильма,
// и редактор комментария, и потому проверяется он отдельно от них обоих.
//
// Контракт (plan.md, раздел 3):
//   function hasComment(comment: string | null): comment is string;
//
// Обрезка внутри проверки — не украшение, а страховка записей, заведённых до этой версии:
// до v14 стёртый комментарий сохранялся пустой строкой, и в живой базе такие строки уже
// лежат. Валидатор (критерий 6) чинит будущее, предикат — прошлое.

import { describe, it, expect } from 'vitest';
import { hasComment } from '@/lib/comment';

describe('hasComment: комментарий есть', () => {
  it('обычный текст — есть', () => {
    expect(hasComment('Смотрел трижды и каждый раз про другое')).toBe(true);
  });

  it('текст в одну букву — тоже есть', () => {
    expect(hasComment('О')).toBe(true);
  });

  it('пробелы по краям комментария не отменяют: внутри есть текст', () => {
    expect(hasComment('  ещё как  ')).toBe(true);
  });

  it('текст в несколько абзацев — есть', () => {
    expect(hasComment('Первый абзац.\n\nВторой абзац.')).toBe(true);
  });
});

describe('hasComment: комментария нет', () => {
  it('null — нет', () => {
    expect(hasComment(null)).toBe(false);
  });

  it('пустая строка — нет', () => {
    expect(hasComment('')).toBe(false);
  });

  it('одни пробелы — нет', () => {
    expect(hasComment('   ')).toBe(false);
  });

  it('одни переносы строк — нет: так выглядит недостёртый абзац', () => {
    expect(hasComment('\n\n')).toBe(false);
  });

  it('пробелы вперемешку с табуляцией и переносами — нет', () => {
    expect(hasComment(' \t\n \r\n ')).toBe(false);
  });
});

describe('hasComment: сужение типа', () => {
  // Предикат объявлен как `comment is string` — иначе страница и редактор писали бы
  // `film.comment!` в каждом месте показа. Проверка компилируется только при сужении:
  // у `string | null` свойства `length` нет.
  it('после проверки комментарий — строка, а не «строка или null»', () => {
    const comment: string | null = 'есть';

    if (!hasComment(comment)) throw new Error('предикат не признал непустой комментарий');

    const length: number = comment.length;
    expect(length).toBe(4);
  });
});
